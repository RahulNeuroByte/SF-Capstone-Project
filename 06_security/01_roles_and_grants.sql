-- Run as ACCOUNTADMIN. Adjust user names before GRANT ROLE statements.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DATA_ENGINEER;
CREATE ROLE IF NOT EXISTS DATA_ANALYST;
CREATE ROLE IF NOT EXISTS DATA_SCIENTIST;
CREATE ROLE IF NOT EXISTS BI_ANALYST;
CREATE ROLE IF NOT EXISTS SECURITY_ADMIN;

GRANT ROLE DATA_ENGINEER TO ROLE SYSADMIN;
GRANT ROLE DATA_ANALYST TO ROLE SYSADMIN;
GRANT ROLE DATA_SCIENTIST TO ROLE SYSADMIN;
GRANT ROLE BI_ANALYST TO ROLE SYSADMIN;
GRANT ROLE SECURITY_ADMIN TO ROLE SYSADMIN;

GRANT USAGE ON DATABASE GLOBRORETAIL_DW TO ROLE DATA_ENGINEER;
GRANT USAGE ON DATABASE GLOBRORETAIL_DW TO ROLE DATA_ANALYST;
GRANT USAGE ON DATABASE GLOBRORETAIL_DW TO ROLE DATA_SCIENTIST;
GRANT USAGE ON DATABASE GLOBRORETAIL_DW TO ROLE BI_ANALYST;
GRANT USAGE ON DATABASE GLOBRORETAIL_DW TO ROLE SECURITY_ADMIN;

GRANT USAGE ON SCHEMA GLOBRORETAIL_DW.CORE TO ROLE DATA_ENGINEER;
GRANT USAGE ON SCHEMA GLOBRORETAIL_DW.CORE TO ROLE DATA_ANALYST;
GRANT USAGE ON SCHEMA GLOBRORETAIL_DW.CORE TO ROLE DATA_SCIENTIST;
GRANT USAGE ON SCHEMA GLOBRORETAIL_DW.CORE TO ROLE BI_ANALYST;
GRANT USAGE ON SCHEMA GLOBRORETAIL_DW.SECURITY TO ROLE SECURITY_ADMIN;
GRANT USAGE ON SCHEMA GLOBRORETAIL_DW.ANALYTICS TO ROLE DATA_ANALYST;
GRANT USAGE ON SCHEMA GLOBRORETAIL_DW.ANALYTICS TO ROLE DATA_SCIENTIST;
GRANT USAGE ON SCHEMA GLOBRORETAIL_DW.ANALYTICS TO ROLE BI_ANALYST;

GRANT USAGE ON WAREHOUSE GR_WH TO ROLE DATA_ENGINEER;
GRANT USAGE ON WAREHOUSE GR_TRANSFORM_WH TO ROLE DATA_ENGINEER;
