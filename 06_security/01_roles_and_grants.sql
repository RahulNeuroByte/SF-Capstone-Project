GRANT SELECT ON ALL VIEWS IN SCHEMA GLOBRORETAIL_DW.SECURITY TO ROLE DATA_SCIENTIST;
GRANT SELECT ON ALL VIEWS IN SCHEMA GLOBRORETAIL_DW.SECURITY TO ROLE BI_ANALYST;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA GLOBRORETAIL_DW.RAW TO ROLE DATA_ENGINEER;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA GLOBRORETAIL_DW.CLEAN TO ROLE DATA_ENGINEER;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA GLOBRORETAIL_DW.CORE TO ROLE DATA_ENGINEER;
GRANT SELECT ON ALL TABLES IN SCHEMA GLOBRORETAIL_DW.OPS TO ROLE DATA_ENGINEER;

-- Future grants keep access aligned for new tables/views.
GRANT SELECT ON FUTURE TABLES IN SCHEMA GLOBRORETAIL_DW.CORE TO ROLE DATA_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GLOBRORETAIL_DW.CORE TO ROLE DATA_SCIENTIST;
